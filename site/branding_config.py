#!/usr/bin/env python3
"""Branding-profile loader for site/build.py.

Reads config/branding.yaml — the single customization point for the
published site's identity, theme, chart palettes, feeds, and analytics —
validates it against the schema below, and exposes helpers that
site/build.py consumes. Stdlib-only, like everything under site/.

Design contract (see docs/customization.md):
  - DEFAULTS below mirrors config/branding.yaml as shipped upstream. A
    missing config file, or any missing key, falls back to the identical
    value — so a fork that deletes half the file still builds the
    upstream-branded site.
  - Unknown keys FAIL the build (fail-loud beats a silently ignored typo).
  - Theme values are an override layer: empty string → styles.css keeps
    owning the value; non-empty → render_branding_css() emits a CSS
    custom-property override block loaded after styles.css.

The YAML-subset parser is shared with tools/compose_prompts.py (same
syntax rules as config/org-profile.yaml; loaded by file path so it works
under both `python3 site/build.py` and the test-suite import).
"""

from __future__ import annotations

import copy
import importlib.util
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
BRANDING_PATH = ROOT / "config" / "branding.yaml"
BRANDING_ASSETS_DIR = Path(__file__).resolve().parent / "branding"


class BrandingError(Exception):
    """Anything wrong with config/branding.yaml. Aborts the build."""


def _yaml_parser():
    """Load parse_yaml_subset from tools/compose_prompts.py by path."""
    src = ROOT / "tools" / "compose_prompts.py"
    if not src.exists():
        raise BrandingError(
            f"cannot parse config/branding.yaml: {src} is missing "
            "(it provides the shared YAML-subset parser)"
        )
    spec = importlib.util.spec_from_file_location("_ctipilot_compose_prompts", src)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.parse_yaml_subset, mod.ProfileError


