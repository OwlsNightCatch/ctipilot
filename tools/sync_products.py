#!/usr/bin/env python3
"""Keep the registry's `product:` records in step with the entry store.

Every entry names the software it concerns in `affected_products[]`, at the
precision a responder needs ("Microsoft SharePoint Server 2019"). That is the
wrong granularity for a pivot: a reader asking "what has happened to
SharePoint?" wants one page, not one per release. This tool turns those
strings into PRODUCT ENTITIES so a product sits beside actors, malware and
campaigns, with its own permalink, coverage timeline, ATT&CK profile and node
in the threat graph.

  python3 tools/sync_products.py            # write the block
  python3 tools/sync_products.py --check    # report drift, exit 1 if any
  python3 tools/sync_products.py --report   # what resolved where

What it writes: one contiguous, marked block of `product:` records at the end
of `entities/registry.yaml`. Everything else in that file is untouched, so
the diff is the products and nothing else.

What it preserves: every curated field on an existing product record —
`name`, `summary`, `aliases`, `relations`, `merged_into`, `first_seen`. The
tool only ADDS the spellings it found in the corpus. Merging two products is
therefore an edit, not a migration: add the loser's name to the winner's
`aliases` (or tombstone it with `merged_into`) and re-run; the entries that
named the old spelling follow, because they were never rewritten.

Registry keys are permanent. This tool never renames one.
"""
from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "site"))

import content_model  # noqa: E402

REGISTRY_PATH = ROOT / "entities" / "registry.yaml"

BLOCK_START = (
    "  # ---------------------------------------------------------------------\n"
    "  # PRODUCTS — affected software as entities.\n"
    "  #\n"
    "  # Generated by tools/sync_products.py from every entry's\n"
    "  # affected_products[]; curated fields (name, summary, aliases,\n"
    "  # relations, merged_into) are read back and preserved, so merging two\n"
    "  # spellings means adding an alias here, never editing an entry.\n"
    "  # ---------------------------------------------------------------------\n"
)
BLOCK_END = "  # --- end PRODUCTS ---\n"

# Seed merges: product families the mechanical rule cannot fold, because the
# difference is a marketing name rather than a version. Canonical name ->
# every spelling the corpus uses for the same product line. Each becomes the
# record's `aliases`, after which resolution is purely registry-driven.
#
# Only same-product-line merges belong here. Two SKUs a vendor advises
# together are still two products (Fortinet FortiOS and FortiProxy stay
# apart); a release codename, an "Enterprise Server" spelling or a renamed
# suite is one product.
